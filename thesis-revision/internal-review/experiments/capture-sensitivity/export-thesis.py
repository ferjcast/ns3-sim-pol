#!/usr/bin/env python3
"""Export verified sensitivity results as thesis tables and vector-plot sources."""
import csv
from decimal import Decimal, ROUND_HALF_UP
import hashlib
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
FIGURES = ROOT/'assets/figures'
DATA = FIGURES/'capture-sensitivity-data'
RULES = [('single_preselected', 'One preselected', 'researchgrey', 'o', 'densely dotted'),
         ('1_of_4', 'Any one of four', 'researchcyan!70!black', 'triangle*', 'dashed'),
         ('2_of_4', '2 of 4', 'researchgrey!65!black', 'diamond*', 'dashdotted'),
         ('3_of_4', '3 of 4', 'researchteal', '*', 'solid'),
         ('4_of_4', '4 of 4', 'researchteal!55!black', 'square*', 'loosely dashed')]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def percent(row, digits=2):
    value = Decimal(row['admitted'])*100/Decimal(row['trials'])
    return str(value.quantize(Decimal(10)**-digits, rounding=ROUND_HALF_UP))


def main():
    verified = json.loads((HERE/'results/verification.json').read_text())
    for name, digest in verified['verified_output_sha256'].items():
        assert sha(HERE/'results'/name) == digest, name
    rows = list(csv.DictReader((HERE/'results/results.csv').open()))

    def one(**filters):
        def matches(row):
            for key, value in filters.items():
                if isinstance(value, bool):
                    if row[key] != str(value): return False
                elif isinstance(value, (int, float)):
                    if not math.isclose(float(row[key]), value, rel_tol=1e-12, abs_tol=1e-12): return False
                elif row[key] != value:
                    return False
            return True
        found = [r for r in rows if matches(r)]
        assert len(found) == 1, (filters, len(found))
        return found[0]

    def reference(truth, rule, common=0):
        return one(block='errors', stage='range_rf_visual', truth_present=truth,
                   rule=rule, fp=.1, fn=.1, error_common=common)

    DATA.mkdir(exist_ok=True)
    table = [r'% Generated by internal-review/experiments/capture-sensitivity/export-thesis.py',
             r'\begin{table}[htbp]', r'    \centering',
             r'    \caption{Admission percentages in 100,000 synthetic trials per context. Recognition errors are independent, with false-positive and missed-detection probabilities 0.1, full visibility, and no missing or dishonest reports.}',
             r'    \label{tab:capture-sensitivity-reference}',
             r'    \begin{tabular}{lrr}', r'        \toprule',
             r'        \textbf{Rule} & \textbf{Valid context (\%)} & \textbf{Invalid context (\%)} \\',
             r'        \midrule']
    for rule, label, *_ in RULES:
        table.append(f'        {label} & {percent(reference(True, rule))} & {percent(reference(False, rule), 3)} '+r'\\')
    table += [r'        \bottomrule', r'    \end{tabular}', r'\end{table}', '']
    table_path = ROOT/'assets/tables/capture-sensitivity-reference.tex'
    table_path.write_text('\n'.join(table))

    def csv_plot(name, points, metric='admit_rate', x_scale=1):
        with (DATA/name).open('w') as stream:
            writer = csv.DictWriter(stream, fieldnames=['x', 'percent', 'low', 'high'])
            writer.writeheader()
            for x, row in points:
                rate = float(row[metric]) if metric == 'admit_rate' else int(row[metric])/int(row['trials'])
                if metric == 'admit_rate':
                    lower, upper = float(row['ci95_low']), float(row['ci95_high'])
                else:
                    n = int(row['trials']); z = 1.959963984540054
                    den = 1+z*z/n
                    centre = (rate+z*z/(2*n))/den
                    half = z*math.sqrt(rate*(1-rate)/n+z*z/(4*n*n))/den
                    lower, upper = max(0, centre-half), min(1, centre+half)
                writer.writerow(dict(x=x*x_scale, percent=100*rate,
                                     low=100*max(0, rate-lower), high=100*max(0, upper-rate)))

    header = r'''% Generated from verified results; compile with latexmk -cd -pdf.
\documentclass[tikz,border=2pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{newtxtext,newtxmath,pgfplots}
\usepgfplotslibrary{groupplots}
% Same base palette as assets/figures/research-approach.tex.
\definecolor{researchteal}{HTML}{009CA6}
\definecolor{researchcyan}{HTML}{59DCE1}
\definecolor{researchgrey}{HTML}{606575}
\pgfplotsset{compat=1.18,every axis/.append style={width=123mm,height=78mm,
    grid=major,major grid style={gray!15},
    tick label style={font=\fontsize{9}{11}\selectfont},
    label style={font=\fontsize{9}{11}\selectfont},
    legend style={font=\fontsize{8}{10}\selectfont,draw=none,
        at={(0.5,1.04)},anchor=south,legend cell align=left}}}
\begin{document}\begin{tikzpicture}
'''

    def series(filename, label, colour, marker='*', line='solid'):
        style = (f'color={colour},line width=1.0pt,{line},mark={marker},mark size=2.1pt,'
                 f'mark options={{solid,draw={colour},fill='+('white' if marker == 'o' else colour)+'}')
        result = (r'\addplot['+style+
                  r',error bars/.cd,y dir=both,y explicit,error bar style={solid,line width=0.6pt}] '
                  r'table[col sep=comma,x=x,y=percent,y error minus=low,y error plus=high] '
                  r'{capture-sensitivity-data/'+filename+'};\n')
        if label is not None:
            result += r'\addlegendentry{'+label+'}\n'
        return result

    correlation = header+r'''\begin{axis}[legend columns=3,xlabel={Shared recognition-error fraction $c$},
    ylabel={Invalid-context admission (\%)},xmin=-0.015,xmax=1.015,
    xtick={0,0.25,0.5,0.75,1},ymode=log,ymin=0.003,ymax=60,
    ytick={0.01,0.1,1,10},yticklabels={0.01,0.1,1,10}]
'''
    for rule, label, colour, marker, line in RULES:
        filename = f'correlation-{rule}.csv'
        csv_plot(filename, [(c, reference(False, rule, c)) for c in [0, .25, .5, .75, 1]])
        correlation += series(filename, label, colour, marker, line)
    correlation += '\\end{axis}\\end{tikzpicture}\\end{document}\n'
    correlation_path = FIGURES/'capture-sensitivity-correlation.tex'
    correlation_path.write_text(correlation)

    availability = header+r'''\begin{groupplot}[
    group style={group size=2 by 1,horizontal sep=7mm},width=61mm,height=54mm,
    xmin=-0.7,xmax=50.7,ymin=0,ymax=100,
    xtick={0,10,25,50},ytick={0,25,50,75,100},legend columns=2,
    title style={at={(0,1.02)},anchor=south west,font=\fontsize{9}{11}\selectfont\bfseries}]
'''
    for metric, title in [('admit_rate', 'Admitted'), ('inconclusive', 'Inconclusive')]:
        if metric == 'admit_rate':
            availability += r'''\nextgroupplot[title={(a) Admitted},ylabel={Valid-context trials (\%)},
    legend style={at={(1.08,1.20)},anchor=south,font=\fontsize{8}{10}\selectfont,draw=none}]
'''
        else:
            availability += r'''\nextgroupplot[title={(b) Inconclusive},yticklabels={}]
'''
        for cm, prefix, colour, marker, line in [(0, 'Independent missingness', 'researchteal', '*', 'solid'),
                                                (1, 'Shared missingness', 'researchgrey', 'square*', 'dashed')]:
            filename = f'availability-{metric}-{cm}.csv'
            csv_plot(filename, [(p, one(block='availability', stage='range_rf_visual', truth_present=True,
                                       rule='3_of_4', missing=p, missing_common=cm, error_common=0))
                                for p in [0, .1, .25, .5]], metric, x_scale=100)
            availability += series(filename, prefix if metric == 'admit_rate' else None, colour, marker, line)
    availability += r'''\end{groupplot}
\path (group c1r1.south west) -- node[midway,anchor=north,yshift=-6mm,
    font=\fontsize{9}{11}\selectfont] {Missing observations per witness (\%)}
    (group c2r1.south east);
\end{tikzpicture}\end{document}
'''
    availability_path = FIGURES/'capture-sensitivity-availability.tex'
    availability_path.write_text(availability)
    exported = [table_path, correlation_path, availability_path]+sorted(DATA.glob('*.csv'))
    record = {'results_sha256': sha(HERE/'results/results.csv'),
              'plot_data_units': 'Percent on y axes and on the availability x axis; interval errors in percentage points.',
              'palette': {'teal': '009CA6', 'cyan': '59DCE1', 'grey': '606575',
                          'source': 'assets/figures/research-approach.tex'},
              'exporter_sha256': sha(Path(__file__)),
              'exported': {str(p.relative_to(ROOT)): sha(p) for p in exported}}
    (HERE/'thesis-export.json').write_text(json.dumps(record, indent=2)+'\n')
    print(f'Exported {len(exported)} verified table, chart-source and data files.')


if __name__ == '__main__':
    main()
